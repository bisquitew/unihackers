// Builds apps/web/src/ro.js from the app's Romanian dictionary, so the website and the app share one set of translations.
// Run: node apps/web/scripts/gen-ro.mjs   (re-run after editing apps/app/src/core/i18n/ro.ts)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
let src = readFileSync(path.join(root, 'apps/app/src/core/i18n/ro.ts'), 'utf8');
src = src
  .replace(/^import .*$/m, 'let captured = {}; const registerDictionary = (_l, e) => { captured = e; };')
  .replace(/:\s*\[string, string\]\[\]/g, '')
  .replace(/:\s*Record<string, string>/g, '');
const entries = new Function(`${src}\nreturn captured;`)();
writeFileSync(path.join(root, 'apps/web/src/ro.js'), `// Generated by scripts/gen-ro.mjs from the app's dictionary. Do not edit; add website-only text to ro-web.js.\nexport const RO = ${JSON.stringify(entries)};\n`);
console.log(`ro.js: ${Object.keys(entries).length} entries`);
